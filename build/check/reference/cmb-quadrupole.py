# Writes cmb-quadrupole.json: the Galaxy's axes in the axes of the background radiation, from three
# full-sky maps of it (too large to keep here; URLs and SHA-256 in the output). Run with numpy and healpy:
#   python cmb-quadrupole.py wmap_ilc_9yr_v5.fits COM_CMB_IQU-commander_1024_R2.02_full.fits \
#     COM_CMB_IQU-smica_1024_R2.02_full.fits > cmb-quadrupole.json
#
# The message defines first-axis as the direction w with the largest average of
# (T(u) − mean T) × ((w·u)² − 1/3) over all directions u: the top eigenvector of
# M = average of (T(u) − mean T) u uᵀ. second-axis is the middle eigenvector, third-axis their cross.
# The monopole and the dipole add nothing to M. The motion of the Sun adds a Doppler quadrupole
# b T0 β² ((d·u)² − 1/3), with b between 1 and about 1.7 depending on how a map was made; whether a map
# still holds it is not always stated, so each map is taken with b = 0, 1 and 1.7. The ends of the
# axes are chosen so that the direction to the Galactic centre has a positive dot with the first two.
import hashlib, json, sys
import numpy as np, healpy as hp

URLS = {
    "wmap_ilc_9yr_v5.fits": "https://lambda.gsfc.nasa.gov/data/map/dr5/dfp/ilc/wmap_ilc_9yr_v5.fits",
    "COM_CMB_IQU-commander_1024_R2.02_full.fits": "https://irsa.ipac.caltech.edu/data/Planck/release_2/all-sky-maps/maps/component-maps/cmb/COM_CMB_IQU-commander_1024_R2.02_full.fits",
    "COM_CMB_IQU-smica_1024_R2.02_full.fits": "https://irsa.ipac.caltech.edu/data/Planck/release_2/all-sky-maps/maps/component-maps/cmb/COM_CMB_IQU-smica_1024_R2.02_full.fits",
}
# the Solar dipole, Planck 2018 I: 3362.08 μK toward (l, b) = (264.021°, 48.253°); T0 from Fixsen (2009)
T0, DIPOLE = 2.72548, 3362.08e-6
beta = DIPOLE / T0
d = hp.ang2vec(264.021, 48.253, lonlat=True)

out = {"about": "Generated by cmb-quadrupole.py from the maps listed; do not edit. Components are Galactic: toward-centre (1,0,0), along-rotation (0,1,0), galactic-pole (0,0,1).", "maps": []}
for path in sys.argv[1:]:
    name = path.split("/")[-1]
    sha = hashlib.sha256(open(path, "rb").read()).hexdigest()
    m = hp.read_map(path, field=0)
    unit = 1e-3 if name.startswith("wmap") else 1.0  # WMAP maps are in mK, Planck maps in K
    u = np.vstack(hp.pix2vec(hp.get_nside(m), np.arange(len(m))))
    t = (m - m.mean()) * unit
    M = (u * t) @ u.T / len(m)
    cases = []
    for b in (0.0, 1.0, 1.7):
        Mc = M - b * T0 * beta**2 * (2 / 15) * (np.outer(d, d) - np.eye(3) / 3)
        w, v = np.linalg.eigh(Mc)
        a1, a2 = v[:, 2] * np.sign(v[0, 2]), v[:, 1] * np.sign(v[0, 1])
        a3 = np.cross(a1, a2)
        cases.append({"doppler": b, "eigenvalues_K": w[::-1].tolist(),
                      "first-axis": a1.tolist(), "second-axis": a2.tolist(), "third-axis": a3.tolist()})
    out["maps"].append({"file": name, "url": URLS.get(name), "sha256": sha, "M_K": M.tolist(), "cases": cases})
print(json.dumps(out, indent=1))
